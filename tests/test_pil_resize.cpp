static int g_fail = 0;

static void check_resize(const char * what, int dw, int dh, const unsigned char * golden) {
    std::vector<float> out((size_t)dw * dh * 3, 0.0f);
    image_preproc::resize_bicubic_pil_u8_hwc(kSrc, 12, 12, out.data(), dh, dw, 3);
    int bad = 0, worst = 0;
    for (size_t i = 0; i < out.size(); i++) {
        const int got = (int)out[i];
        const int want = (int)golden[i];
        const int d = got > want ? got - want : want - got;
        if (d) {
            bad++;
            if (d > worst) worst = d;
        }
        // The values must be integral: PIL's 8-bit path rounds, it does not
        // carry sub-integer precision into the caller.
        if (out[i] != (float)got) {
            std::printf("  FAIL %s: element %zu = %.6f is not integral\n", what, i, out[i]);
            g_fail++;
            return;
        }
    }
    if (bad) {
        std::printf("  FAIL %s (12x12 -> %dx%d): %d of %zu elements differ, max %d\n", what, dw, dh, bad, out.size(),
                    worst);
        g_fail++;
    }
}

int main() {
    std::printf("pil bicubic resize: 4 golden resizes from Pillow\n");
    check_resize("downscale 5x5", 5, 5, kDown5x5);
    check_resize("downscale 7x4", 7, 4, kDown7x4);
    check_resize("upscale 16x16", 16, 16, kUp16x16);
    check_resize("identity 12x12", 12, 12, kSame12x12);

    // Partition of unity: every kernel is renormalised to sum to 1, so a
    // constant image must survive any resize exactly. This is an algebraic
    // invariant, not a tolerance — it fails outright if the border
    // renormalisation is dropped (dev guide 2c).
    {
        std::vector<unsigned char> flat(9 * 7 * 3, 137);
        std::vector<float> out(23 * 5 * 3, 0.0f);
        image_preproc::resize_bicubic_pil_u8_hwc(flat.data(), 7, 9, out.data(), 5, 23, 3);
        for (size_t i = 0; i < out.size(); i++) {
            if (out[i] != 137.0f) {
                std::printf("  FAIL constant image: element %zu = %.3f, want 137\n", i, out[i]);
                g_fail++;
                break;
            }
        }
    }

    // Range: cubic ringing must be clipped, never wrapped or left out of [0,255].
    {
        std::vector<unsigned char> edge(16 * 16 * 3);
        for (int y = 0; y < 16; y++)
            for (int x = 0; x < 16; x++)
                for (int c = 0; c < 3; c++) edge[((size_t)y * 16 + x) * 3 + c] = (x < 8) ? 0 : 255;
        std::vector<float> out(9 * 9 * 3, 0.0f);
        image_preproc::resize_bicubic_pil_u8_hwc(edge.data(), 16, 16, out.data(), 9, 9, 3);
        for (size_t i = 0; i < out.size(); i++) {
            if (out[i] < 0.0f || out[i] > 255.0f) {
                std::printf("  FAIL hard edge: element %zu = %.3f out of [0,255]\n", i, out[i]);
                g_fail++;
                break;
            }
        }
    }

    if (g_fail) {
        std::printf("FAILED: %d check(s)\n", g_fail);
        return 1;
    }
    std::printf("OK\n");
    return 0;
}
