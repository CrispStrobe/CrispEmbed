// test_pil_resize.cpp — pins image_preproc::resize_bicubic_pil_u8_hwc against
// Pillow itself.
//
// Golden vectors below are the literal output of
//   Image.fromarray(src).resize((w, h), Image.BICUBIC)
// on a deterministic 12x12 RGB pattern (a ramp on R, a ramp on G, a 3x3 checker
// on B — no PRNG, so the fixture travels inline). Pillow is the reference: HF's
// SLOW image processors (`resample: 3`) resample through it, and it is NOT the
// same resampler as torchvision's antialiased bicubic, which is what
// resize_bicubic_u8_hwc implements. On the LFM2.5-VL pages the two differ by up
// to 18/255 on thousands of pixels.
//
// Three properties this guards, each independently able to change the output
// with no shape or range violation:
//   * clip8 BETWEEN the horizontal and vertical passes (carrying float through
//     both is most of that 18/255);
//   * the per-output-pixel tap COUNT, not one fixed ceil(2*support) per axis;
//   * border handling — clamp the tap RANGE and renormalise, rather than clamp
//     the index and replicate the edge pixel.
//
// Hermetic and weight-free: no model, no file I/O.

