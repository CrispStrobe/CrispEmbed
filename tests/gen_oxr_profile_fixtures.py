#!/usr/bin/env python3
"""Regenerate small independent Pillow/NumPy OXR preprocessing gold values.

Usage: python tests/gen_oxr_profile_fixtures.py /path/to/pinned/modeling_oxr.py
No model, PyTorch import or model forward is involved. The resize-size function
is extracted verbatim from the pinned source; image bytes come from Pillow.
"""
import argparse
import ast
import hashlib
import math
from pathlib import Path

import numpy as np
import PIL
from PIL import Image


def numbers(values):
    return ",".join(str(int(x)) for x in values)


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("source", type=Path)
    parser.add_argument("--output", type=Path, default=Path("tests/fixtures/oxr/preprocess_gold.h"))
    args = parser.parse_args()
    raw = args.source.read_bytes()
    tree = ast.parse(raw)
    cls = next(node for node in tree.body if isinstance(node, ast.ClassDef) and node.name == "OXRVisualTokenizer")
    resize = next(node for node in cls.body if isinstance(node, ast.FunctionDef) and node.name == "smart_resize")
    resize.decorator_list = []
    scope = {"math": math}
    exec(compile(ast.fix_missing_locations(ast.Module(body=[resize], type_ignores=[])), str(args.source), "exec"), scope)
    source_resize = scope["smart_resize"]
    lines = [
        "// Generated by tests/gen_oxr_profile_fixtures.py; do not derive gold from native code.",
        f"// Pillow {PIL.__version__}; NumPy {np.__version__}; source SHA256 {hashlib.sha256(raw).hexdigest()}",
        "#pragma once", "#include <cstdint>", "#include <vector>", "// clang-format off",
        "namespace oxr_gold {", "struct resize_case { int w,h,ch,rw,rh; std::vector<uint8_t> input,expected; };",
        "inline const std::vector<resize_case> resizes = {",
    ]
    for w, h, ch, rw, rh in [(7, 5, 3, 13, 9), (19, 17, 3, 5, 7), (9, 11, 4, 6, 15),
                             (8, 3, 1, 17, 5), (7, 5, 3, 7, 5), (1, 11, 4, 9, 3)]:
        values = np.array([(i * 73 + (i // 7) * 19 + 17) % 256 for i in range(w*h*ch)], dtype=np.uint8)
        image = Image.frombytes({1:"L",3:"RGB",4:"RGBA"}[ch], (w,h), values.tobytes()).convert("RGB")
        expected = np.asarray(image.resize((rw,rh), Image.Resampling.BILINEAR)).reshape(-1)
        lines.append("{%d,%d,%d,%d,%d,{%s},{%s}}," % (w,h,ch,rw,rh,numbers(values),numbers(expected)))
    lines += ["};", "struct size_case { int h,w,rh,rw; };", "inline const std::vector<size_case> sizes = {"]
    for h,w in [(512,512),(1536,1024),(14,31),(32,7000),(32,6400),(6400,32),(100,200),(80,48),(10000,700),(449,527),(1151,879)]:
        rh,rw=source_resize(h,w,factor=32,min_pixels=200704,max_pixels=921600)
        lines.append("{%d,%d,%d,%d}," % (h,w,rh,rw))
    lines += ["};"]
    w,h,ch=17,23,4
    values=np.array([(i*41+(i//5)*17+13)%256 for i in range(w*h*ch)],dtype=np.uint8)
    rh,rw=source_resize(h,w,factor=32,min_pixels=1024,max_pixels=1024)
    image=Image.frombytes("RGBA",(w,h),values.tobytes()).convert("RGB").resize((rw,rh),Image.Resampling.BILINEAR)
    arr=np.asarray(image).transpose(2,0,1)
    arr=(arr.astype(np.float64)*(1.0/255.0)).astype(np.float32)
    arr=(arr-np.float32(.5))/np.float32(.5)
    gh,gw=rh//16,rw//16
    patches=arr.reshape(1,1,3,gh//2,2,16,gw//2,2,16).transpose(0,3,6,4,7,2,1,5,8).reshape(gh*gw,768).copy()
    lines += [f"inline constexpr int patch_w={w},patch_h={h},patch_ch={ch},patch_rh={rh},patch_rw={rw};",
              "inline const std::vector<uint8_t> patch_input={"+numbers(values)+"};",
              "inline const std::vector<uint32_t> patch_expected_bits={"+numbers(patches.view(np.uint32).reshape(-1))+"};",
              "} // namespace oxr_gold", ""]
    args.output.parent.mkdir(parents=True,exist_ok=True)
    args.output.write_text("\n".join(lines))
    print(f"wrote {len(lines)} source lines, {args.output.stat().st_size} bytes")


if __name__ == "__main__":
    main()
