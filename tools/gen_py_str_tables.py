#!/usr/bin/env python3
"""Generate src/core/py_str_tables.h: CPython str predicates as code-point ranges.

The OXR native document port reproduces Python str.isspace/isalpha/isalnum/
isdecimal (and therefore re's Unicode \\s, \\w, \\d) exactly. Run with the
Python whose unicodedata version the reference helper uses (CPython 3.12,
Unicode 15.0, as in the upstream vLLM image and the hosted parity lane):
    python tools/gen_py_str_tables.py > src/core/py_str_tables.h
"""
import sys
import unicodedata


def ranges(pred):
    out, start = [], None
    for cp in range(0x110000):
        ok = pred(chr(cp))
        if ok and start is None:
            start = cp
        elif not ok and start is not None:
            out.append((start, cp - 1))
            start = None
    if start is not None:
        out.append((start, 0x10FFFF))
    return out


def emit(name, rs):
    print(f"static const py_cp_range {name}[] = {{")
    for i in range(0, len(rs), 6):
        print("    " + " ".join(f"{{0x{a:04X}, 0x{b:04X}}}," for a, b in rs[i:i + 6]))
    print("};")


print("// src/core/py_str_tables.h -- GENERATED by tools/gen_py_str_tables.py, do not edit.")
print(f"// CPython {sys.version_info.major}.{sys.version_info.minor} str predicates, "
      f"unicodedata {unicodedata.unidata_version}.")
print("// Unicode data license: src/core/third_party/unicode/LICENSE.")
print("#pragma once")
print("#include <cstdint>")
print("namespace py_str {")
print("struct py_cp_range { uint32_t lo, hi; };")
print(f'static const char k_unidata_version[] = "{unicodedata.unidata_version}";')
emit("k_isspace", ranges(str.isspace))
emit("k_isalpha", ranges(str.isalpha))
emit("k_isalnum", ranges(str.isalnum))
emit("k_isdecimal", ranges(str.isdecimal))
print("} // namespace py_str")
