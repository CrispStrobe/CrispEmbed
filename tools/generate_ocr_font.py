#!/usr/bin/env python3
"""Regenerate the original two-glyph font used only by invisible OCR text.

Requires fontTools during development, never at runtime. No third-party font
data is used: glyph zero is empty; glyph one is a 1000-unit square. PDF text
rendering mode 3 prevents painting. Its real metrics give text selection a
predictable rectangle, while each document supplies its own Unicode CMap.
"""

from io import BytesIO
from pathlib import Path

from fontTools.fontBuilder import FontBuilder
from fontTools.pens.ttGlyphPen import TTGlyphPen


def main():
    builder = FontBuilder(1000, isTTF=True)
    builder.setupGlyphOrder([".notdef", "ocrbox"])
    empty = TTGlyphPen(None).glyph()
    pen = TTGlyphPen(None)
    pen.moveTo((0, 0))
    pen.lineTo((1000, 0))
    pen.lineTo((1000, 1000))
    pen.lineTo((0, 1000))
    pen.closePath()
    builder.setupGlyf({".notdef": empty, "ocrbox": pen.glyph()})
    builder.setupHorizontalMetrics({".notdef": (1000, 0), "ocrbox": (1000, 0)})
    builder.setupHorizontalHeader(ascent=1000, descent=0)
    builder.setupCharacterMap({0x20: "ocrbox"})
    builder.setupOS2(sTypoAscender=1000, sTypoDescender=0, usWinAscent=1000,
                    usWinDescent=0, sCapHeight=1000)
    builder.setupNameTable({"familyName": "CrispOcrInvisible", "styleName": "Regular",
                           "uniqueFontIdentifier": "CrispOcrInvisible-1.0",
                           "fullName": "CrispOcrInvisible", "psName": "CrispOcrInvisible",
                           "version": "Version 1.0"})
    builder.setupPost()
    builder.setupMaxp()
    # A CIDFontType2 uses its PDF CIDToGIDMap, not a TrueType cmap table.
    del builder.font["cmap"]
    builder.font["head"].created = 2082844800
    builder.font["head"].modified = 2082844800
    builder.font.recalcTimestamp = False
    output = BytesIO()
    builder.font.save(output)
    data = output.getvalue()
    rows = ["    " + ", ".join(f"0x{v:02x}" for v in data[i:i + 12]) + ","
            for i in range(0, len(data), 12)]
    header = ("// Generated by tools/generate_ocr_font.py. Original geometric glyphs;\n"
              "// no external font data or runtime font installation is required.\n"
              "#pragma once\n\n"
              "static constexpr unsigned char ocr_pdf_font[] = {\n"
              + "\n".join(rows) + "\n};\n")
    (Path(__file__).resolve().parents[1] / "src/ocr_pdf_font.h").write_text(header)


if __name__ == "__main__":
    main()
