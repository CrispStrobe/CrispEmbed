#!/usr/bin/env python3
"""Generate tests/arabic_morph_disambig_fixture.h for the disambiguation contract test.

Developer tooling. Writes a hand-made disambiguation model for the synthetic
database of tests/test_arabic_morph.cpp with disambig_train.write_model_logp,
and the posteriors that disambig_train.posteriors (the Python reference of
the native forward-backward) gives for the test sentences:

    python tools/arabic_morph/gen_disambig_fixture.py
"""
from __future__ import annotations

import json
import math
import os
import sys
import tempfile
from pathlib import Path

HERE = Path(__file__).resolve().parent
ROOT = HERE.parents[1]
OUT = ROOT / "tests" / "arabic_morph_disambig_fixture.h"
sys.path.insert(0, str(HERE))
import disambig_train as dt  # noqa: E402

SPEC = [("pos", "value"), ("prc2", "flag")]
TAGS = ["<s>", "noun|0", "noun|1", "noun_prop|0", "digit|0", "punc|0", "<oov>"]
# Transition probabilities by previous tag (rows sum to 1 before the log).
TRANS = {
    "<s>": {"noun|0": 0.25, "noun|1": 0.1, "noun_prop|0": 0.25, "digit|0": 0.2, "punc|0": 0.15, "<oov>": 0.05},
    "noun|0": {"<s>": 0.4, "noun|0": 0.2, "noun_prop|0": 0.1, "punc|0": 0.2, "<oov>": 0.1},
    "noun|1": {"<s>": 0.4, "noun|0": 0.3, "punc|0": 0.3},
    "noun_prop|0": {"<s>": 0.4, "noun|0": 0.1, "noun_prop|0": 0.2, "punc|0": 0.2, "<oov>": 0.1},
    "digit|0": {"<s>": 0.1, "noun|0": 0.8, "noun_prop|0": 0.05, "punc|0": 0.05},
    "punc|0": {"<s>": 0.1, "noun|0": 0.05, "noun_prop|0": 0.8, "digit|0": 0.05},
    "<oov>": {"<s>": 0.5, "noun|0": 0.25, "noun_prop|0": 0.25},
}
LEXP = [("noun", "كِتَاب", 0.5), ("noun_prop", "كتاب", 0.4), ("noun_prop", "وكتاب", 0.01),
        ("<oov>", "<oov>", 1.0)]
UNSEEN = {"noun": 1e-4, "noun_prop": 1e-3, "digit": 1.0, "punc": 1.0, "<oov>": 1e-6}


def key(lex, pos, prc2=None):
    k = [None] * len(dt.KEY_FEATURES)
    k[dt.FEATURE_INDEX["lex"]] = lex
    k[dt.FEATURE_INDEX["pos"]] = pos
    k[dt.FEATURE_INDEX["prc2"]] = prc2
    return tuple(k)


# The fixture database's analyses (backoff ADD_PROP) of the test words, in
# analyzer order; only lex, pos and prc2 enter the model (prc2 is not in the
# fixture's ORDER, so it is absent: flag 0).
ANALYSES = {
    "2024": [key("2024", "digit", "0")],
    "«": [key("«", "punc", "0")],
    "كتاب": [key("كِتَاب", "noun"), key("كتاب", "noun_prop")],
    "وكتاب": [key("كِتَاب", "noun"), key("وكتاب", "noun_prop"), key("كتاب", "noun_prop")],
    "  ": [],
}
SENTENCES = [["2024", "كتاب"], ["«", "كتاب", "  "], ["وكتاب"], ["كتاب", "«", "2024", "وكتاب"]]


def main() -> None:
    n = len(TAGS)
    # Listed transitions; every other one backs off to 1e-3 * U(cur), U uniform.
    uni = [math.log(1.0 / n)] * n
    backoff = [math.log(1e-3)] * n
    index = {t: i for i, t in enumerate(TAGS)}
    entries = [(index[a], index[b], math.log(p)) for a, row in TRANS.items() for b, p in row.items()]
    lexp = [(p, lx, math.log(v)) for p, lx, v in LEXP]
    unseen = {p: math.log(v) for p, v in UNSEEN.items()}
    with tempfile.TemporaryDirectory() as tmp:
        path = os.path.join(tmp, "fixture.cmdis")
        dt.write_model_logp(path, SPEC, TAGS, uni, backoff, entries, lexp, unseen, {"fixture": True})
        data = Path(path).read_bytes()
        model = dt.read_model(path)
    lines = [
        "// Generated by tools/arabic_morph/gen_disambig_fixture.py; do not edit.",
        "// A hand-made disambiguation model for the synthetic database of",
        "// test_arabic_morph.cpp and the posteriors of the Python reference",
        "// (disambig_train.posteriors) for the test sentences.",
        "#pragma once",
        "",
        "#include <cstddef>",
        "",
        "// The CI compares this file byte for byte with the generator output.",
        "// clang-format off",
        f"static const unsigned char k_disambig_model[{len(data)}] = {{",
    ]
    for i in range(0, len(data), 16):
        lines.append("    " + " ".join(f"0x{b:02x}," for b in data[i:i + 16]))
    lines += ["};", "", "struct disambig_expected {", "    const char * words; // tab-separated",
              "    const char * scores; // per word: per analysis 'rank:score', words separated by '|'", "};", "",
              "static const disambig_expected k_disambig_cases[] = {"]
    for sent in SENTENCES:
        post = dt.posteriors(model, [ANALYSES[w] for w in sent])
        parts = []
        for cands, of, g in post:
            order = sorted(range(len(g)), key=lambda c: (-g[c], c))
            rank = {c: r for r, c in enumerate(order)}
            parts.append(",".join(f"{rank[c]}:{g[c]:.6f}" for c in of))
        words = "\\t".join(sent)
        lines.append(f'    {{ "{words}", "{"|".join(parts)}" }},')
    lines += ["};", "// clang-format on", ""]
    OUT.write_text("\n".join(lines), encoding="utf-8", newline="\n")
    print(json.dumps({"fixture_bytes": len(data), "tags": n, "cases": len(SENTENCES)}))


if __name__ == "__main__":
    main()
