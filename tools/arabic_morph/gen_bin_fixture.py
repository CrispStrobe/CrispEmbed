#!/usr/bin/env python3
"""Generate tests/arabic_morph_bin_fixture.h for the binary-database contract test.

Developer tooling. Converts the synthetic ALMOR database of
tests/test_arabic_morph.cpp (without its *_logprob tokens) with
models/convert-camel-morph-db.py's build_binary and a small profile, and
projects that test's camel_tools-produced expected outputs onto the profile:

    python tools/arabic_morph/gen_bin_fixture.py
"""
from __future__ import annotations

import importlib.util
import json
from pathlib import Path
import re

ROOT = Path(__file__).resolve().parents[2]
TEST = ROOT / "tests" / "test_arabic_morph.cpp"
OUT = ROOT / "tests" / "arabic_morph_bin_fixture.h"
PROFILE = ("diac", "lex", "pos", "prc2", "gen", "num", "form_gen", "form_num", "source")


def load_converter():
    spec = importlib.util.spec_from_file_location("convert_camel_morph_db", ROOT / "models" / "convert-camel-morph-db.py")
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module


def main() -> None:
    conv = load_converter()
    text = TEST.read_text(encoding="utf-8")
    db = re.search(r'k_db = R"DB\(\n(.*?)\)DB";', text, re.S).group(1)
    data, _ = conv.drop_prob_fields(db.encode("utf-8"))
    binary, _ = conv.build_binary(data, PROFILE)
    cases = re.findall(r'\{ (\d), "((?:[^"\\]|\\.)*)",\s*R"J\((.*?)\)J" \}', text, re.S)
    lines = [
        "// Generated by tools/arabic_morph/gen_bin_fixture.py; do not edit.",
        "// The synthetic database of test_arabic_morph.cpp in the binary format",
        f"// (profile: {', '.join(PROFILE)}) and that test's camel_tools outputs",
        "// projected onto the profile.",
        "#pragma once",
        "",
        "#include <cstddef>",
        "",
        "// The CI compares this file byte for byte with the generator output.",
        "// clang-format off",
        f"static const unsigned char k_bin_db[{len(binary)}] = {{",
    ]
    for i in range(0, len(binary), 16):
        lines.append("    " + " ".join(f"0x{b:02x}," for b in binary[i:i + 16]))
    lines += ["};", "", "struct bin_case {", "    int backoff;", "    const char * word;", "    const char * json;",
              "};", "", "static const bin_case k_bin_cases[] = {"]
    keep = set(PROFILE)
    for backoff, word, expected in cases:
        word = word.encode("utf-8").decode("unicode_escape").encode("latin-1").decode("utf-8")
        projected = [{k: v for k, v in a.items() if k in keep} for a in json.loads(expected)]
        out = json.dumps(projected, ensure_ascii=False, separators=(",", ":"))
        lines.append(f'    {{ {backoff}, {json.dumps(word, ensure_ascii=False)}, R"J({out})J" }},')
    lines += ["};", "// clang-format on", ""]
    OUT.write_text("\n".join(lines), encoding="utf-8", newline="\n")
    print(json.dumps({"fixture_bytes": len(binary), "cases": len(cases)}))


if __name__ == "__main__":
    main()
