#!/usr/bin/env python3
"""Generate src/arabic_morph_tables.h: camel_tools' UNICODE_PUNCT_SYMBOL_CHARSET.

camel_tools.utils.charsets builds the set from unicodedata categories P* and S*
of the running Python. The native analyzer uses this table for _is_punc and
_has_punc, so regenerate it with the Python/Unicode version of the reference
(camel_tools 1.6.0 on CPython 3.12, Unicode 15.0.0).

    python tools/arabic_morph/gen_tables.py > src/arabic_morph_tables.h
"""
import sys
import unicodedata


def ranges(pred):
    out, start = [], None
    for cp in range(0x110000):
        if pred(cp):
            if start is None:
                start = cp
        elif start is not None:
            out.append((start, cp - 1))
            start = None
    if start is not None:
        out.append((start, 0x10FFFF))
    return out


def main():
    rs = ranges(lambda cp: unicodedata.category(chr(cp))[0] in "PS")
    w = sys.stdout.write
    w("// Generated by tools/arabic_morph/gen_tables.py; do not edit.\n")
    w(f"// Unicode {unicodedata.unidata_version} general categories P* and S* (camel_tools\n")
    w("// UNICODE_PUNCT_SYMBOL_CHARSET), as inclusive code point ranges.\n")
    w("#pragma once\n\n#include <cstdint>\n\nnamespace arabic_morph_tables {\n\n")
    w(f'static const char k_unicode_version[] = "{unicodedata.unidata_version}";\n\n')
    w("struct cp_range {\n    uint32_t lo, hi;\n};\n\n")
    w("static const cp_range k_punct_symbol[] = {\n")
    for i in range(0, len(rs), 4):
        w("    " + " ".join(f"{{0x{a:X}, 0x{b:X}}}," for a, b in rs[i:i + 4]) + "\n")
    w("};\n\n} // namespace arabic_morph_tables\n")


if __name__ == "__main__":
    main()
