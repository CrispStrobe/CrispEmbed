#!/usr/bin/env python3
"""Generate tests/unlimited_ocr2_text_fixture.h for tests/test_unlimited_ocr2_text.cpp.

Inputs: the original tokenizer.json (baidu/Unlimited-OCR-2 @04647c7a) and a trial receipt
(tests/results/unlimited-ocr2/trial.json) whose reference.cases hold the ORIGINAL model's
generated ids and its decoded text (tokenizer.decode(gen, skip_special_tokens=False)).
Emits only the vocab pieces those ids (plus a few edge-case ids) use, the ids, the original
text, and the expected clean() rendering (independent Python implementation below).
When the `tokenizers` package is importable, the original text is re-checked against it.

    python3 tools/unlimited-ocr2/gen_text_fixture.py tokenizer.json \
        tests/results/unlimited-ocr2/trial.json tests/unlimited_ocr2_text_fixture.h
"""
import ast
import json
import re
import sys

EXTRA_IDS = [1, 128805, 128816, 128830]  # EOS, <|EOT|>, <|ref|>, <CHILD> (edge cases)


def c_str(s):
    out = []
    for b in s.encode('utf-8'):
        ch = chr(b)
        if 32 <= b < 127 and ch not in '\\"?':
            out.append(ch)
        else:
            out.append('\\%03o' % b)
    return '"' + ''.join(out) + '"'


HEADER = re.compile(r'^[A-Za-z0-9_\- ]+(<LEVEL[0-9]+>)?(\[[0-9,. \-]*\])?$')


def clean(raw):
    out, i, n = '', 0, len(raw)
    while i < n:
        if raw.startswith('<PAGE>', i):
            if out:
                out = out.rstrip('\n') + '\n\n'
            i += 6
        elif raw.startswith('<BLOCK>', i):
            i += 7
            f = raw.find('<FORK>', i)
            if f >= 0 and HEADER.match(raw[i:f]):
                i = f + 6
        elif raw.startswith('<FORK>', i):
            i += 6
        elif raw.startswith('<CHILD>', i):
            i += 7
        else:
            out += raw[i]
            i += 1
    return out


def main():
    tok_path, trial_path, out_path = sys.argv[1:4]
    tj = json.load(open(tok_path, encoding='utf-8'))
    vocab = {v: k for k, v in tj['model']['vocab'].items()}
    for a in tj['added_tokens']:
        vocab[a['id']] = a['content']
    trial = json.load(open(trial_path, encoding='utf-8'))
    try:
        from tokenizers import Tokenizer
        tk = Tokenizer.from_file(tok_path)
    except ImportError:
        tk = None
    cases, used = [], set(EXTRA_IDS)
    for c in trial['reference']['cases']:
        ids = c['ids'] if isinstance(c['ids'], list) else ast.literal_eval(c['ids'])
        if tk is not None:
            assert tk.decode(ids, skip_special_tokens=False) == c['text'], c['id']
        cases.append((c['id'], ids, c['text'], clean(c['text'])))
        used.update(ids)
    L = ['// Generated by tools/unlimited-ocr2/gen_text_fixture.py -- do not edit.',
         '// Pieces: baidu/Unlimited-OCR-2 @04647c7a tokenizer.json (only the ids used here).',
         '// Cases: original-model ids + decoded text from the Kaggle trial receipt',
         '// (tests/results/unlimited-ocr2/trial.json, reference.cases).',
         '#pragma once', '#include <cstdint>', '', 'namespace uocr2_text_fixture {',
         'struct piece { int32_t id; const char * text; };', 'static const piece kPieces[] = {']
    for i in sorted(used):
        L.append('    { %d, %s },' % (i, c_str(vocab[i])))
    L.append('};')
    for k, (cid, ids, text, cl) in enumerate(cases):
        L.append('static const int32_t kIds%d[] = { %s };' % (k, ', '.join(map(str, ids))))
    L.append('struct text_case { const char * name; const int32_t * ids; int n; const char * text; const char * clean; };')
    L.append('static const text_case kCases[] = {')
    for k, (cid, ids, text, cl) in enumerate(cases):
        L.append('    { %s, kIds%d, %d,' % (c_str(cid), k, len(ids)))
        L.append('      %s,' % c_str(text))
        L.append('      %s },' % c_str(cl))
    L.append('};')
    L.append('} // namespace uocr2_text_fixture')
    open(out_path, 'w', encoding='utf-8', newline='\n').write('\n'.join(L) + '\n')
    print('wrote', out_path, len(used), 'pieces', len(cases), 'cases')


if __name__ == '__main__':
    main()
