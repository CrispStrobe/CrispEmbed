#!/usr/bin/env python3
"""Capture the actual pinned Moebius/PixelHacker pipeline on a hosted worker.

This does not reimplement a UNet, VAE, scheduler, or guidance equation. It loads
the upstream modules, captures the random tensors generated by an ordinary run,
then replays those identical tensors through the unchanged original pipeline
with hooks. The two final float outputs must be bit identical. The raw little-
endian F32/CHW files and reference.json are consumed by test-latent-inpaint.

Use a separate environment/process for each original's pinned Diffusers version.
PixelHacker's original Flash Linear Attention requires a compatible CUDA worker.
Large capture artifacts must remain on the hosted worker/artifact service.
"""

