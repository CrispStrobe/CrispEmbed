from latent_inpaint_contract import (CASES, CONTRACT, RESOLUTION, fixture, fixture_identity,
                                    load_contract, model_record, sha256, verify_checkpoint, verify_source)


def check_dependencies(model, contract, allowed=None):
    """allowed: explicit {package: version} deviations from the frozen pins
    (default none). Each one used is recorded under versions["deviations"]."""
    expected = contract["source"][model]
    versions, deviations = {}, {}
    allowed = allowed or {}
    for package, version in expected["dependencies"].items():
        actual = importlib.metadata.version(package)
        versions[package] = actual
        if actual.split("+")[0] != version:
            if allowed.get(package) != actual.split("+")[0]:
                raise ValueError(f"original dependency version differs: {package}: {actual} != {version}")
            deviations[package] = {"contract": version, "actual": actual}
    if deviations:
        versions["deviations"] = deviations
    import diffusers

    package_root = Path(diffusers.__file__).resolve().parent
    for relative, row in expected["diffusers_files"].items():
        path = package_root / relative
        if path.stat().st_size != row["bytes"] or sha256(path) != row["sha256"]:
            raise ValueError(f"original Diffusers implementation differs: {relative}")
    for package in ("numpy", "Pillow", "timm", "einops", "transformers", "accelerate"):
        try:
            versions[package] = importlib.metadata.version(package)
        except importlib.metadata.PackageNotFoundError:
            versions[package] = None
    return versions


def load_original(model_name, source_dir, checkpoint, vae_checkpoint, device, allowed=None):
    contract = load_contract()
    verify_source(source_dir, model_name, contract)
    verify_checkpoint(checkpoint, model_record(model_name, contract))
    verify_checkpoint(vae_checkpoint, model_record("sdxl_vae", contract))
    versions = check_dependencies(model_name, contract, allowed)
    import torch
    import yaml
    from diffusers import AutoencoderKL, DDIMScheduler

    source_dir = Path(source_dir).resolve()
    sys.path.insert(0, str(source_dir))
    config_path = source_dir / ("config/model_cfg/moebius.yaml" if model_name == "moebius"
                                else "config/PixelHacker_sdvae_f8d4.yaml")
    config = yaml.safe_load(config_path.read_text(encoding="utf-8"))
    if model_name == "moebius":
        from removal.v1_2.removal_model import build_removal_model
        from removal.v1_2.pipeline import RemovalSDXLPipeline_BatchMode

        model = build_removal_model(config, 20)
        pipeline_class = RemovalSDXLPipeline_BatchMode
        model_keyword = "removal_model"
    else:
        from utils import build_model
        from pipeline import PixelHacker_Pipeline

        model = build_model(config, 20)
        pipeline_class = PixelHacker_Pipeline
        model_keyword = "model"

    def load_state(module, path, record):
        state = torch.load(path, map_location="cpu", weights_only=True)
        expected = {row["name"]: row for row in record["state"]}
        if not isinstance(state, dict) or set(state) != set(expected):
            raise ValueError("original checkpoint state keys differ")
        for name, value in state.items():
            row = expected[name]
            if list(value.shape) != row["shape"] or str(value.dtype).removeprefix("torch.") != row["dtype"]:
                raise ValueError(f"original checkpoint state shape/dtype differs: {name}")
            if value.is_floating_point() and not torch.isfinite(value).all():
                raise ValueError(f"nonfinite original weight: {name}")
        module.load_state_dict(state, strict=True)
        for name, value in module.state_dict().items():
            if not torch.equal(value, state[name].to(value.dtype)):
                raise AssertionError(f"original load changed a tensor: {name}")
        del state

    load_state(model, checkpoint, model_record(model_name, contract))
    vae = AutoencoderKL.from_config(contract["vae_config"])
    load_state(vae, vae_checkpoint, model_record("sdxl_vae", contract))
    scheduler_kwargs = dict(contract["scheduler"])
    scheduler_kwargs.pop("class")
    scheduler_kwargs.pop("eta")
    scheduler = DDIMScheduler(**scheduler_kwargs)
    pipe = pipeline_class(**{model_keyword: model}, vae=vae, scheduler=scheduler,
                          device=device, dtype=torch.float32)
    return pipe, model, vae, versions


def canonical_chw(value, branch, module_name):
    """Only a layout adapter for observed module outputs; no model arithmetic."""
    import torch

    if hasattr(value, "sample"):
        value = value.sample
    elif isinstance(value, (tuple, list)):
        value = value[0]
    if not isinstance(value, torch.Tensor):
        raise ValueError(f"unsupported original hook output: {module_name}")
    if value.dtype != torch.float32:
        raise ValueError(f"original floating stage is not F32: {module_name}")
    if value.shape[0] not in (1, 2):
        raise ValueError("unexpected original batch size")
    value = value[branch if value.shape[0] == 2 else 0]
    if module_name.endswith("g_norm_swish_gate"):
        # Original fused module returns [N, heads, head_v]; native stores CHW.
        if value.ndim != 3:
            raise ValueError("unexpected fused gate layout")
        value = value.reshape(value.shape[0], -1)
    if value.ndim == 1:
        return value[:, None, None]
    if value.ndim == 2:
        length, channels = value.shape
        if length == 10:
            return value.transpose(0, 1).reshape(channels, 1, length)
        side = int(length ** 0.5)
        if side * side != length:
            raise ValueError("non-square spatial attention sequence")
        return value.transpose(0, 1).reshape(channels, side, side)
    if value.ndim == 3:
        return value
    raise ValueError(f"unsupported original tensor rank: {module_name}")


class Saver:
    def __init__(self, directory):
        self.directory = directory
        self.rows = []
        self.names = set()

    def save(self, name, value, filename=None):
        import numpy as np
        import torch

        if name in self.names:
            raise ValueError(f"duplicate captured stage: {name}")
        self.names.add(name)
        if isinstance(value, torch.Tensor):
            value = value.detach().cpu().contiguous().numpy()
        array = np.ascontiguousarray(value, dtype="<f4")
        if array.ndim != 3 or not np.isfinite(array).all():
            raise ValueError(f"stage must be finite CHW: {name}")
        filename = filename or f"stage-{len(self.rows):04d}.f32"
        data = array.tobytes()
        (self.directory / filename).write_bytes(data)
        row = {"name": name, "file": filename, "shape": list(array.shape), "bytes": len(data),
               "sha256": hashlib.sha256(data).hexdigest(), "min": float(array.min()),
               "max": float(array.max()), "l2": float(np.linalg.norm(array.astype(np.float64)))}
        self.rows.append(row)
        return row


@contextmanager
def random_tape(tape, replay=False):
    """Observe or replay random draws at library boundaries, without changing math."""
    import torch
    import diffusers.models.autoencoders.vae as vae_module

    old_posterior, old_like, old_randn = vae_module.randn_tensor, torch.randn_like, torch.randn
    posterior_count = 0
    consumed = set()

    def emit(name, original, args, kwargs):
        if name in consumed:
            raise AssertionError(f"unexpected repeated random draw: {name}")
        consumed.add(name)
        if not replay:
            result = original(*args, **kwargs)
            tape[name] = result.detach().clone()
            return result
        if name not in tape:
            raise AssertionError(f"missing frozen random draw: {name}")
        return tape[name].clone()

    def posterior(*args, **kwargs):
        nonlocal posterior_count
        name = ("posterior_image", "posterior_masked")[posterior_count] if posterior_count < 2 else "unexpected_posterior"
        posterior_count += 1
        return emit(name, old_posterior, args, kwargs)

    def like(*args, **kwargs):
        return emit("latent_noise", old_like, args, kwargs)

    def normal(*args, **kwargs):
        shape = args[0] if len(args) == 1 and isinstance(args[0], (tuple, list)) else args
        if tuple(shape) == (1, 4, 1, 1):
            return emit("offset_noise", old_randn, args, kwargs)
        return old_randn(*args, **kwargs)

    vae_module.randn_tensor, torch.randn_like, torch.randn = posterior, like, normal
    try:
        yield
        if consumed != {"posterior_image", "posterior_masked", "latent_noise", "offset_noise"}:
            raise AssertionError("original random draw inventory differs")
    finally:
        vae_module.randn_tensor, torch.randn_like, torch.randn = old_posterior, old_like, old_randn


def wanted_module(name):
    if name == "embedding_layer":
        return True
    if name in ("diff_model", "diff_model.time_proj", "diff_model.time_embedding", "diff_model.encoder_hid_proj",
                "diff_model.conv_in", "diff_model.conv_norm_out", "diff_model.conv_out", "diff_model.mid_block"):
        return True
    if re.fullmatch(r"diff_model\.(down_blocks|up_blocks)\.\d+", name):
        return True
    if re.search(r"\.(resnets\.\d+(?:\.conv[12])?|(?:downsamplers|upsamplers)\.0|attentions\.\d+)$", name):
        return True
    return re.search(r"\.transformer_blocks\.0(?:\.(?:attn1|attn2|ff)(?:\.g_norm_swish_gate)?)?$", name) is not None


def capture_case(pipe, model, vae, model_name, case_name, directory, contract):
    import numpy as np
    from PIL import Image
    import torch

    directory.mkdir(parents=True, exist_ok=False)
    rgb, mask = fixture(case_name)
    image_pil = Image.frombytes("RGB", (RESOLUTION, RESOLUTION), rgb)
    mask_pil = Image.frombytes("L", (RESOLUTION, RESOLUTION), mask)
    image_pil.save(directory / "input.png")
    mask_pil.save(directory / "fill-mask.png")
    (directory / "input.rgb").write_bytes(rgb)
    (directory / "fill-mask.u8").write_bytes(mask)
    image, fill_mask, masked = pipe._denoise_preprocess(image_pil, mask_pil)
    options = dict(model_record(model_name, contract)["defaults"])
    options["num_steps"] = options.pop("steps")
    options["guidance_scale"] = options.pop("guidance")
    options["mute"] = True
    tape = {}
    torch.manual_seed(contract["reference"]["seed"])
    if image.device.type == "cuda":
        torch.cuda.synchronize(image.device)
    start = time.perf_counter()
    with torch.inference_mode(), random_tape(tape):
        ordinary = pipe._denoise_steps(image, fill_mask, masked, **options).clone()
    if image.device.type == "cuda":
        torch.cuda.synchronize(image.device)
    ordinary_seconds = time.perf_counter() - start
    saver, input_saver = Saver(directory), Saver(directory)
    alpha_record = saver.save("sampler.alphas_cumprod", pipe.noise_scheduler.alphas_cumprod[:, None, None],
                              "sampler.alphas_cumprod.f32")
    inputs = {"image": input_saver.save("image", image[0], "input.image.f32"),
              "mask": input_saver.save("mask", fill_mask[0].float(), "input.mask.f32")}
    for name in ("posterior_image", "posterior_masked", "latent_noise", "offset_noise"):
        inputs[name] = input_saver.save(name, tape[name][0], "input." + name + ".f32")
    index = {"step": -1, "moments": 0}
    handles = []
    old_add_noise, old_step = pipe.noise_scheduler.add_noise, pipe.noise_scheduler.step

    def add_noise(original, noise, timestep):
        saver.save("vae.image.latents", original[0])
        value = old_add_noise(original, noise, timestep)
        saver.save("latent.initial", value[0])
        return value

    def scheduler_step(*args, **kwargs):
        saver.save("sampler.noise." + str(index["step"]), args[0][0])
        result = old_step(*args, **kwargs)
        value = result[0] if isinstance(result, tuple) else result.prev_sample
        saver.save("sampler.step." + str(index["step"]), value[0])
        return result

    def before_model(module, args):
        index["step"] += 1
        if index["step"] == 0:
            saver.save("vae.masked.latents", args[0][0, 5:9])

    def after_model(module, args, result):
        value = result.sample
        if value.shape[0] != 2:
            raise ValueError("reference requires the original two-arm CFG batch")
        for branch, label in enumerate(("unconditional", "conditional")):
            saver.save("unet.step" + str(index["step"]) + "." + label, value[branch])

    def moments(module, args, result):
        which = ("image", "masked")[index["moments"]]
        index["moments"] += 1
        saver.save("vae." + which + ".moments", result[0])

    def decoder(module, args, result):
        saver.save("vae.decoded", result[0])

    handles.append(model.register_forward_pre_hook(before_model))
    handles.append(model.register_forward_hook(after_model))
    handles.append(vae.quant_conv.register_forward_hook(moments))
    handles.append(vae.decoder.register_forward_hook(decoder))
    if case_name in contract["reference"]["full_intermediates"]:
        for name, module in model.named_modules():
            if not wanted_module(name):
                continue

            def hook(module, args, result, name=name):
                if index["step"] == 0:
                    for branch, label in enumerate(("unconditional", "conditional")):
                        saver.save("unet.step.0." + label + "." + name, canonical_chw(result, branch, name))

            handles.append(module.register_forward_hook(hook))
    pipe.noise_scheduler.add_noise, pipe.noise_scheduler.step = add_noise, scheduler_step
    try:
        with torch.inference_mode(), random_tape(tape, replay=True):
            observed = pipe._denoise_steps(image, fill_mask, masked, **options)
    finally:
        pipe.noise_scheduler.add_noise, pipe.noise_scheduler.step = old_add_noise, old_step
        for handle in handles:
            handle.remove()
    if not torch.equal(ordinary, observed):
        raise AssertionError("original random replay/observer neutrality failed")
    generated = (ordinary[0].permute(1, 2, 0).clamp(0, 1) * 255).to(torch.uint8).cpu().numpy()
    original_rgb = np.frombuffer(rgb, dtype=np.uint8).reshape(RESOLUTION, RESOLUTION, 3)
    fill = np.frombuffer(mask, dtype=np.uint8).reshape(RESOLUTION, RESOLUTION) == 255
    composed = np.where(fill[:, :, None], generated, original_rgb).astype(np.uint8)
    if not np.array_equal(composed[~fill], original_rgb[~fill]):
        raise AssertionError("known pixels changed during exact-mask composition")
    (directory / "final.generated.rgb").write_bytes(generated.tobytes())
    (directory / "final.composited.rgb").write_bytes(composed.tobytes())
    Image.fromarray(generated).save(directory / "generated.png")
    Image.fromarray(composed).save(directory / "composited.png")
    settings = dict(model_record(model_name, contract)["defaults"])
    settings["timesteps"] = [int(t) for t in pipe.noise_scheduler.timesteps.tolist()][
        settings["steps"] - int(settings["steps"] * settings["strength"]):]
    report = {
        "schema": "crispembed-latent-inpaint-reference-case-v1", "model": model_name,
        "source_contract_sha256": sha256(CONTRACT),
        "checkpoint_sha256": model_record(model_name, contract)["checkpoint"]["sha256"],
        "vae_checkpoint_sha256": model_record("sdxl_vae", contract)["checkpoint"]["sha256"],
        "fixture": fixture_identity(case_name), "settings": settings, "inputs": inputs,
        "scheduler_alphas": alpha_record,
        "rgb": {"file": "input.rgb", "shape": [RESOLUTION, RESOLUTION, 3], "sha256": hashlib.sha256(rgb).hexdigest()},
        "fill_mask": {"file": "fill-mask.u8", "shape": [RESOLUTION, RESOLUTION], "sha256": hashlib.sha256(mask).hexdigest()},
        "stages": saver.rows,
        "final_generated_rgb": {"file": "final.generated.rgb", "shape": [RESOLUTION, RESOLUTION, 3],
                                "sha256": sha256(directory / "final.generated.rgb")},
        "final_composited_rgb": {"file": "final.composited.rgb", "shape": [RESOLUTION, RESOLUTION, 3],
                                 "sha256": sha256(directory / "final.composited.rgb")},
        "original_seconds": ordinary_seconds,
        "ordinary_original_forwards": 1, "observed_original_forwards": 1,
        "hook_and_random_replay_neutrality_bit_exact": True,
        "known_rgb_exact": True, "complete": True, "native_qualified": False,
    }
    if index["step"] + 1 != len(settings["timesteps"]) or index["moments"] != 2:
        raise AssertionError("original stage/step call counts differ")
    (directory / "reference.json").write_text(json.dumps(report, indent=2) + "\n", encoding="utf-8")
    return report


def run(args):
    contract = load_contract()
    output = args.output
    if output.exists():
        raise ValueError("reference output directory already exists")
    if args.model == "pixelhacker" and not args.device.startswith("cuda"):
        raise ValueError("PixelHacker original Flash Linear Attention requires a compatible CUDA worker")
    os.environ.setdefault("CUBLAS_WORKSPACE_CONFIG", ":4096:8")
    import torch

    torch.set_num_threads(args.threads)
    torch.set_num_interop_threads(1)
    torch.use_deterministic_algorithms(True)
    torch.backends.cuda.matmul.allow_tf32 = False
    torch.backends.cudnn.allow_tf32 = False
    torch.backends.cudnn.benchmark = False
    allowed = dict(item.split("==", 1) for item in args.allow_dependency)
    pipe, model, vae, versions = load_original(args.model, args.source_dir, args.checkpoint, args.vae_checkpoint,
                                               args.device, allowed)
    output.mkdir(parents=True, exist_ok=False)
    report = {"schema": "crispembed-latent-inpaint-original-v1", "model": args.model,
              "source_commit": contract["source"][args.model]["commit"],
              "source_contract_sha256": sha256(CONTRACT), "versions": versions,
              "python": platform.python_version(), "torch_config": torch.__config__.show(),
              "device": args.device, "threads": args.threads, "cases": [],
              "dumper_sha256": sha256(__file__), "helper_sha256": sha256(Path(__file__).with_name("latent_inpaint_contract.py")),
              "producer": {"github_sha": os.environ.get("GITHUB_SHA"), "github_run_id": os.environ.get("GITHUB_RUN_ID")},
              "complete": False, "native_qualified": False, "representative_quality_qualified": False}
    (output / "report.json").write_text(json.dumps(report, indent=2) + "\n", encoding="utf-8")
    for name in args.cases:
        try:
            capture_case(pipe, model, vae, args.model, name, output / name, contract)
        except BaseException as error:
            report["failure"] = {"case": name, "type": type(error).__name__, "message": str(error)}
            (output / "report.json").write_text(json.dumps(report, indent=2) + "\n", encoding="utf-8")
            raise
        report["cases"].append({"id": name, "file": name + "/reference.json", "sha256": sha256(output / name / "reference.json")})
        (output / "report.json").write_text(json.dumps(report, indent=2) + "\n", encoding="utf-8")
        print("Captured " + args.model + "/" + name, flush=True)
    report["complete"] = True
    (output / "report.json").write_text(json.dumps(report, indent=2) + "\n", encoding="utf-8")
    return report


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--model", choices=("moebius", "pixelhacker"), required=True)
    parser.add_argument("--source-dir", type=Path, required=True)
    parser.add_argument("--checkpoint", type=Path, required=True)
    parser.add_argument("--vae-checkpoint", type=Path, required=True)
    parser.add_argument("--output", type=Path, required=True)
    parser.add_argument("--device", default="cuda:0")
    parser.add_argument("--threads", type=int, default=2)
    parser.add_argument("--cases", nargs="+", choices=CASES, default=list(CASES))
    # PixelHacker's upstream pins (torch 2.3.0 with triton 3.2.0) cannot import
    # FLA 0.3.2 (torch 2.3 inductor vs triton 3 AttrsDescriptor). An explicit,
    # recorded deviation such as torch==2.6.0 (triton 3.2.0's release) is the
    # only way to run the unchanged original; the contract stays frozen.
    parser.add_argument("--allow-dependency", action="append", default=[], metavar="PKG==VERSION")
    args = parser.parse_args()
    if any("==" not in item for item in args.allow_dependency):
        parser.error("--allow-dependency takes PKG==VERSION")
    if not 1 <= args.threads <= 8 or len(args.cases) != len(set(args.cases)):
        parser.error("threads must be 1..8 and cases must be unique")
    run(args)


if __name__ == "__main__":
    main()
