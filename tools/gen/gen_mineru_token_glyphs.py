"""Generate src/mineru_token_glyphs.h: DejaVu Sans glyph atlas for table tokens.

Upstream table_image_processor draws "[XXXX]" tokens (alphabet ACDGHKTWXYZ +
2345678) with Pillow/FreeType using the first available font (DejaVu Sans on
Linux). This atlas stores Pillow's 64 px rendering metrics and 8-bit coverage
masks so the native route can draw legible tokens without FreeType. It is an
approximation (not pixel-identical at other sizes). DejaVu fonts: Bitstream
Vera license, see licenses/dejavu-fonts-LICENSE.

usage: python gen_mineru_token_glyphs.py DejaVuSans.ttf OUT.h
"""
import sys
from PIL import ImageFont

REF = 64
CHARS = "[]ACDGHKTWXYZ2345678"
font = ImageFont.truetype(sys.argv[1], size=REF)
rows = []
data = []
for ch in CHARS:
    l, t, r, b = font.getbbox(ch)
    adv = font.getlength(ch)
    mask = font.getmask(ch, mode="L")
    w, h = mask.size
    off = len(data)
    data.extend(mask[i] for i in range(w * h))
    rows.append((ord(ch), adv, l, t, r, b, w, h, off))
kern = {}
with open(sys.argv[2], "w") as f:
    f.write("// Generated by tools/gen/gen_mineru_token_glyphs.py from DejaVu Sans; do not edit.\n")
    f.write("// DejaVu fonts license: licenses/dejavu-fonts-LICENSE (Bitstream Vera).\n#pragma once\n#include <cstdint>\n")
    f.write(f"static const int mineru_glyph_ref_size = {REF};\n")
    f.write("struct mineru_glyph { char ch; double advance; int l, t, r, b, w, h, offset; };\n")
    f.write("static const mineru_glyph mineru_glyphs[] = {\n")
    for c, adv, l, t, r, b, w, h, off in rows:
        f.write(f"    {{ {c}, {adv!r}, {l}, {t}, {r}, {b}, {w}, {h}, {off} }},\n")
    f.write("};\nstatic const uint8_t mineru_glyph_masks[] = {\n")
    for i in range(0, len(data), 32):
        f.write("    " + ",".join(str(x) for x in data[i:i + 32]) + ",\n")
    f.write("};\n")
print(len(rows), "glyphs", len(data), "bytes")
