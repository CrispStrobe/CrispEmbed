"""Generate src/mineru_equation_big_table.h from the pinned try_fix_equation_big.

Each upstream `re.sub(PATTERN, REPL, latex)` line uses a pattern that matches
exactly one literal string. The generator derives that literal, verifies the
pattern fully matches it (and only via a literal), and records CPython's
expanded replacement, preserving upstream order (including its quirks such as
the replacement `\\biggm\\[`).
"""
import ast, re, sys, inspect
from mineru_vl_utils.post_process import equation_big

src = inspect.getsource(equation_big)
calls = []
for node in ast.walk(ast.parse(src)):
    if isinstance(node, ast.Call) and getattr(node.func, "attr", "") == "sub":
        pat, repl = node.args[0].value, node.args[1].value
        calls.append((node.lineno, pat, repl))
calls.sort()

def literal(pat):
    out, i = [], 0
    while i < len(pat):
        c = pat[i]
        if c == "\\":
            out.append(pat[i + 1]); i += 2
        elif c in ".^$*+?[]()|":
            raise ValueError(pat)
        else:
            out.append(c); i += 1
    return "".join(out)

def cxx(s):
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'

rows = []
for _, pat, repl in calls:
    lit = literal(pat)
    assert re.fullmatch(pat, lit), pat
    rows.append((lit, re.sub(pat, repl, lit)))
with open(sys.argv[1], "w") as f:
    f.write("// Generated by tools/gen/gen_mineru_equation_big.py from mineru-vl-utils\n")
    f.write("// c9797cde8f54cc48306196fc6aebe73ea31dd4a3 equation_big.py (Apache-2.0). Do not edit.\n")
    f.write("#pragma once\nstatic const char * const mineru_equation_big_table[][2] = {\n")
    for a, b in rows:
        f.write(f"    {{ {cxx(a)}, {cxx(b)} }},\n")
    f.write("};\n")
print(len(rows), "substitutions")
