"""Generate src/pyunicode_tables.h from the running CPython's str predicates.

The tables reproduce the exact code-point predicates used by CPython's str
methods and its ``re`` module (Unicode mode) so native ports of Python string
algorithms behave identically. Regenerate with the Python version whose
behaviour is the parity reference; the version is recorded in the header.
"""
import sys
import unicodedata

def ranges(pred):
    out, start = [], None
    for c in range(0x110000):
        ok = pred(c)
        if ok and start is None:
            start = c
        elif not ok and start is not None:
            out.append((start, c - 1)); start = None
    if start is not None:
        out.append((start, 0x10FFFF))
    return out

def is_surrogate(c):
    return 0xD800 <= c <= 0xDFFF

alnum = ranges(lambda c: not is_surrogate(c) and chr(c).isalnum())
decimal = ranges(lambda c: not is_surrogate(c) and chr(c).isdecimal())
space = [c for c in range(0x110000) if not is_surrogate(c) and chr(c).isspace()]
lower_full, lower_simple, pool = [], [], []
# Final_Sigma context (CPython unicodeobject.c handle_capital_sigma uses
# _PyUnicode_IsCased / _PyUnicode_IsCaseIgnorable). Derived black-box from
# str.lower() itself so the tables match the running CPython exactly:
#   ("A"+c+"Σ") -> final sigma iff c is case-ignorable or (cased);
#   ("1"+c+"Σ") -> final sigma iff c is not ignorable and cased.
def _final(prefix, c):
    return (prefix + chr(c) + "\u03a3").lower()[-1] == "\u03c2"

import re
for c in range(0x110000):
    if is_surrogate(c):
        continue
    s = chr(c)
    low = s.lower()
    if low != s:
        lower_full.append((c, len(pool), len(low)))
        pool.extend(ord(x) for x in low)
# Simple (1:1) lowercase as used by sre's case-insensitive matching.
import ctypes
for c in range(0x110000):
    if is_surrogate(c):
        continue
    s = chr(c)
    low = s.lower()
    simple = ord(low) if len(low) == 1 else c
    if len(low) != 1:
        # CPython's simple mapping for multi-char full lowercase (only U+0130).
        simple = 0x69 if c == 0x130 else c
    if simple != c:
        lower_simple.append((c, simple))

def ranges_of(pred):
    return ranges(lambda c: not is_surrogate(c) and pred(c))

sigma_ignorable = ranges(lambda c: not is_surrogate(c) and _final("A", c) and not _final("1", c))
sigma_cased = ranges(lambda c: not is_surrogate(c) and _final("1", c))

def arr(name, ctype, rows, per=8):
    lines = [f"static const {ctype} {name}[] = {{"]
    for i in range(0, len(rows), per):
        lines.append("    " + ", ".join(rows[i:i + per]) + ",")
    lines.append("};")
    return "\n".join(lines)

with open(sys.argv[1], "w", encoding="utf-8") as f:
    f.write("// Generated by tools/gen/gen_pyunicode_tables.py; do not edit.\n")
    f.write(f"// CPython {sys.version.split()[0]}, Unicode {unicodedata.unidata_version}.\n")
    f.write("#pragma once\n#include <cstdint>\n\nnamespace pyunicode_tables {\n")
    f.write(f'static const char * const python_version = "{sys.version.split()[0]}";\n')
    f.write(f'static const char * const unicode_version = "{unicodedata.unidata_version}";\n')
    f.write(arr("alnum_ranges", "uint32_t", [f"0x{a:X}, 0x{b:X}" for a, b in alnum], 6) + "\n")
    f.write(arr("decimal_ranges", "uint32_t", [f"0x{a:X}, 0x{b:X}" for a, b in decimal], 6) + "\n")
    f.write(arr("space_points", "uint32_t", [f"0x{c:X}" for c in space], 10) + "\n")
    f.write(arr("lower_full_index", "uint32_t", [f"0x{c:X}, {o}, {n}" for c, o, n in lower_full], 4) + "\n")
    f.write(arr("lower_full_pool", "uint32_t", [f"0x{c:X}" for c in pool], 10) + "\n")
    f.write(arr("lower_simple_map", "uint32_t", [f"0x{c:X}, 0x{s:X}" for c, s in lower_simple], 6) + "\n")
    f.write(arr("sigma_ignorable_ranges", "uint32_t", [f"0x{a:X}, 0x{b:X}" for a, b in sigma_ignorable], 6) + "\n")
    f.write(arr("sigma_cased_ranges", "uint32_t", [f"0x{a:X}, 0x{b:X}" for a, b in sigma_cased], 6) + "\n")
    f.write("} // namespace pyunicode_tables\n")
