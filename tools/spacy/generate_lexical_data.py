#!/usr/bin/env python3
"""Reproduce the small compiled lexical supplement under the frozen oracle.

Bundle v1 already contains scalar lowercase and the five lexical predicates.
This supplement contains spaCy's reserved StringStore symbols and CPython's
regex decimal/alphanumeric and contextual-final-sigma predicates. It changes
neither the original bundle nor the authenticated fixture contract.
"""
import argparse
import hashlib
import json
import platform
from pathlib import Path
import unicodedata

import spacy
from spacy.symbols import IDS


def ranges(predicate):
    result, start = [], None
    for cp in range(0x110000):
        accepted = not 0xD800 <= cp <= 0xDFFF and predicate(chr(cp))
        if accepted and start is None:
            start = cp
        elif not accepted and start is not None:
            result.append((start, cp - 1))
            start = None
    if start is not None:
        result.append((start, 0x10FFFF))
    return result


def generate():
    if (platform.python_version(), unicodedata.unidata_version, spacy.__version__) != (
        "3.12.14", "15.0.0", "3.8.18"
    ):
        raise ValueError("Use the exact CPython3.12.14 / Unicode15.0.0 / spaCy3.8.18 reference environment")
    symbols = sorted(IDS.items())
    symbol_digest = hashlib.sha256(json.dumps(symbols, ensure_ascii=False, separators=(",", ":")).encode()).hexdigest()
    lines = [
        "// Generated by tools/spacy/generate_lexical_data.py; do not edit.",
        "// CPython 3.12.14 / Unicode 15.0.0; spaCy 3.8.18.",
        "// spaCy source: 43311999028032fd81bef77a75fdb4fa96803c98 (MIT).",
        f"// Reserved-symbol JSON SHA-256: {symbol_digest}",
        "// clang-format off", "#pragma once", "#include <cstdint>", "#include <utility>",
        "namespace spacy_lexical_data {",
        "static const std::pair<const char *, std::uint64_t> symbols[] = {",
    ]
    for name, value in symbols:
        lines.append("    { " + json.dumps(name, ensure_ascii=False) + f", {value} " + "},")
    lines.append("};")
    predicates = {
        "decimal": str.isdecimal,
        "word": lambda s: s.isalnum() or s == "_",
        "space": str.isspace,
        "sigma_ignorable": lambda s: ("A" + s + "Σ").lower().endswith("ς") and not ("1" + s + "Σ").lower().endswith("ς"),
        "sigma_cased": lambda s: ("1" + s + "Σ").lower().endswith("ς"),
    }
    for name, predicate in predicates.items():
        values = ranges(predicate)
        lines.append(f"static const std::uint32_t {name}[][2] = {{")
        lines.extend(f"    {{ 0x{start:X}, 0x{end:X} }}," for start, end in values)
        lines.append("};")
    lines.append("} // namespace spacy_lexical_data")
    lines.append("// clang-format on")
    return "\n".join(lines) + "\n"


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--output", type=Path, required=True)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    content = generate()
    if args.check:
        if args.output.read_text(encoding="utf-8") != content:
            raise SystemExit("Lexical supplement differs from the pinned reference")
    else:
        args.output.write_text(content, encoding="utf-8")
