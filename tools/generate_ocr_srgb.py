#!/usr/bin/env python3
"""Generate the native archival output intent with LittleCMS via Pillow.

The profile is computed from the standard sRGB primaries and tone curves; no
third-party profile file is copied. Pillow/LittleCMS are development tools only.
The ICC header date is fixed so repeated generation is reproducible with the
same LittleCMS version. The optional ICC profile ID is computed per ICC.1.
"""

import hashlib
from pathlib import Path
import struct

from PIL import ImageCms, features


def main():
    profile = bytearray(ImageCms.ImageCmsProfile(ImageCms.createProfile("sRGB")).tobytes())
    profile[24:36] = struct.pack(">6H", 2000, 1, 1, 0, 0, 0)
    profile[84:100] = bytes(16)
    digest_input = bytearray(profile)
    digest_input[44:48] = bytes(4)
    digest_input[64:68] = bytes(4)
    profile[84:100] = hashlib.md5(digest_input).digest()
    rows = ["    " + ", ".join(f"0x{v:02x}" for v in profile[i:i + 12]) + ","
            for i in range(0, len(profile), 12)]
    header = ("// Generated by tools/generate_ocr_srgb.py using LittleCMS "
              + features.version("littlecms2") + ".\n"
              "// Standard sRGB output intent; no runtime color-management dependency.\n"
              "#pragma once\n\n"
              "static constexpr unsigned char ocr_pdf_srgb[] = {\n"
              + "\n".join(rows) + "\n};\n")
    (Path(__file__).resolve().parents[1] / "src/ocr_pdf_srgb.h").write_text(header)


if __name__ == "__main__":
    main()
